import numpy
from skimage.measure import find_contours

from fractal_types import (IterMap, NormMap, HeightMapMM, DepthsMM, QuantileProbs, QuantileDepthsMM, ZLevelMM,
                           ZLevelsMM, GridShape, Contour, ContourList, ContoursByLevel)


# (ny, nx) int64, 1..max_iter  в  (ny, nx) float64 мм от -zmax/max_iter...-zmax.
def iters_to_heightmap_mm(iters: IterMap, max_iter: int, zmax_mm: float) -> HeightMapMM:
    norm: NormMap = iters.astype(numpy.float64) / float(max_iter)   # (ny, nx), 1/max_iter … 1.0
    return -norm * float(zmax_mm)


# Выбор уровней по квантилям глубин
def auto_z_levels(heightmap_mm: HeightMapMM, n_levels: int, min_depth_mm: float) -> ZLevelsMM:
    depths: DepthsMM = (-heightmap_mm).ravel()                  # (ny*nx,)
    depths = depths[depths >= float(min_depth_mm)]              # (k,)

    if depths.size == 0 or n_levels <= 0:
        return []

    # квантили
    qs: QuantileProbs = numpy.linspace(0.15, 1, n_levels)
    lev_depths: QuantileDepthsMM = numpy.quantile(depths, qs)

    # округляем, убираем повторяющиеся, сортируем по возрастанию
    z_unique = numpy.unique(numpy.round(-lev_depths, 3))
    z_levels: ZLevelsMM = sorted(z_unique, reverse=True)
    return z_levels


def extract_contours_by_level(heightmap_mm: HeightMapMM, z_levels: ZLevelsMM) -> ContoursByLevel:
    out: ContoursByLevel = {}
    for z in z_levels:
        contours: ContourList = find_contours(heightmap_mm, level=z)  # list[(m, 2) float64]
        out[z] = contours
    return out


def smooth_contour_chaikin(points: Contour, iterations: int = 2, closed: bool = True) -> Contour:
    pts = numpy.asarray(points, dtype=numpy.float64)
    min_pts = 3 if closed else 2
    if pts.ndim != 2 or pts.shape[0] < min_pts or pts.shape[1] != 2:
        return pts

    for _ in range(int(iterations)):
        if closed:
            # для замкнутого контура дублируем первую точку в конец
            pts_closed = numpy.vstack([pts, pts[0]])
            p0 = pts_closed[:-1]
            p1 = pts_closed[1:]

            Q = 0.75 * p0 + 0.25 * p1
            R = 0.25 * p0 + 0.75 * p1

            # чередуем Q и R: Q0, R0, Q1, R1 и т.д.
            new_pts = numpy.empty((2 * len(p0), 2), dtype=numpy.float64)
            new_pts[0::2] = Q
            new_pts[1::2] = R
        else:
            # для открытого контура считаем внутренние ребра
            p0 = pts[:-1]
            p1 = pts[1:]

            Q = 0.75 * p0 + 0.25 * p1
            R = 0.25 * p0 + 0.75 * p1

            # поочерёдно соединяем точки из разных групп
            mid_pts = numpy.empty((2 * len(p0), 2), dtype=numpy.float64)
            mid_pts[0::2] = Q
            mid_pts[1::2] = R

            # сохраняем истинные крайние точки текущей итерации по краям
            new_pts = numpy.vstack([pts[0], mid_pts[1:-1], pts[-1]])

        pts = new_pts

    return pts


def contours_to_gcode_mach3(contours_by_level: ContoursByLevel,
                            heightmap_shape: GridShape,
                            board_width_mm: float,
                            board_height_mm: float,
                            safe_z: float = 5.0,
                            feed_xy: int = 800,
                            feed_z: int = 300,
                            spindle_rpm: int = 12000,
                            min_contour_len_mm: float = 8.0,
                            smooth_enabled: bool = False,
                            smooth_iterations: int = 3,
                            max_segment_len_mm: float = 3.0,
                            filename: str = "newton_contours_mach3.nc") -> str:

    ny, nx = heightmap_shape
    # мм на один шаг сетки
    dx: float = board_width_mm / (nx - 1)
    dy: float = board_height_mm / (ny - 1)

    lines: list[str] = []
    lines.append("( Newton Fractal Contours )")
    lines.append("( Generated by Newton Fractal CNC Generator )")
    lines.append("G21 (mm)")
    lines.append("G90 (absolute)")
    lines.append("G17 (XY plane)")
    lines.append(f"G0 Z{safe_z:.3f}")
    lines.append(f"M3 S{int(spindle_rpm)}")
    lines.append("G4 P2")

    # проходим от более высоких к более низким
    z_level: ZLevelMM
    for z_level in sorted(contours_by_level.keys(), reverse=True):
        contours: ContourList = contours_by_level[z_level]
        lines.append(f"( --- Z level {z_level:.3f} mm --- )")

        contour: Contour
        for contour in contours:
            if contour is None or len(contour) < 2:
                continue

            if z_level >= 0:
                continue

            # safe z
            lines.append(f"G0 Z{safe_z:.3f}")

            # сглаживание одного контура
            if smooth_enabled:
                contour = smooth_contour_chaikin(contour, iterations=smooth_iterations, closed=True)

            # длина контура
            length: float = 0.0
            for i in range(1, len(contour)):
                dy_i: float = (contour[i, 0] - contour[i - 1, 0]) * dy  # столбец 0 = y
                dx_i: float = (contour[i, 1] - contour[i - 1, 1]) * dx  # столбец 1 = x
                length += numpy.hypot(dx_i, dy_i)

            if length < min_contour_len_mm:
                continue

            # стартовая точка
            y0, x0 = contour[0]
            X0: float = x0 * dx
            Y0: float = y0 * dy

            lines.append(f"G0 Z{safe_z:.3f}")
            lines.append(f"G0 X{X0:.3f} Y{Y0:.3f}")
            lines.append(f"G1 Z{z_level:.3f} F{feed_z}")

            prev_x: float = X0
            prev_y: float = Y0

            for y, x in contour[1:]:  # дробные индексы сетки
                X: float = x * dx  # мм
                Y: float = y * dy  # мм

                dist: float = numpy.hypot(X - prev_x, Y - prev_y)

                if dist > max_segment_len_mm:
                    # разрыв контура и безопасный переход
                    lines.append(f"G0 Z{safe_z:.3f}")
                    lines.append(f"G0 X{X:.3f} Y{Y:.3f}")
                    lines.append(f"G1 Z{z_level:.3f} F{feed_z}")
                else:
                    lines.append(f"G1 X{X:.3f} Y{Y:.3f} F{feed_xy}")

                prev_x, prev_y = X, Y

            lines.append(f"G0 Z{safe_z:.3f}")

    lines.append(f"G0 Z{safe_z:.3f}")
    lines.append("M5")
    lines.append("G0 X0 Y0")
    lines.append("M30")

    with open(filename, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    return filename
